import { chromium } from 'playwright-core';
const URL = process.env.SMOKE_URL ?? 'http://127.0.0.1:4173/';
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? '/usr/bin/google-chrome', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
await p.goto(URL); await p.waitForSelector('.splash.gone', { timeout: 30000 });
await p.waitForFunction(() => { const m = /(\d+)\/(\d+) loaded/.exec(document.querySelector('[data-testid="radar-bar"]')?.textContent ?? ''); return m && +m[1] >= Math.min(8, +m[2]); }, null, { timeout: 60000 });
await p.click('.radarbar .play'); await p.locator('[aria-label="Radar frame"]').fill('9'); await p.waitForTimeout(1500);
await p.screenshot({ path: 'screenshots/v7-mobile-map-top.png' });
await p.locator('[aria-label="Radar frame"]').fill('2'); await p.waitForTimeout(1500);
await p.screenshot({ path: 'screenshots/v7-mobile-radar-frame-a.png' });
await p.locator('[aria-label="Radar frame"]').fill('7'); await p.waitForTimeout(1500);
await p.screenshot({ path: 'screenshots/v7-mobile-radar-frame-b.png' });
await p.click('.tabs >> text=Chasers'); await p.waitForTimeout(2500);
await p.screenshot({ path: 'screenshots/v7-mobile-chasers-sheet.png' }); await p.click('.tabs >> text=Chasers');
await p.evaluate(() => window.scrollTo(0, 560)); await p.waitForTimeout(600);
await p.screenshot({ path: 'screenshots/v7-mobile-peek.png' });
await p.locator('[data-testid="faq"]').scrollIntoViewIfNeeded(); await p.click('[data-testid="faq"] details:nth-child(2) summary'); await p.waitForTimeout(500);
await p.screenshot({ path: 'screenshots/v7-mobile-faq.png' });
await b.close(); console.log('ok');
